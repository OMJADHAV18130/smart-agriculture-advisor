"""
FastAPI application for the Smart Agriculture Advisory Expert System.

Endpoints:
  GET  /health   - liveness check plus loaded rule count and thresholds
  GET  /goals    - goal options offered for backward chaining
  POST /analyze  - runs forward chaining (+ optional backward chaining)

The rule engine lives in engine.py and the knowledge in knowledge_base.py;
this module only handles HTTP, validation, and formatting.
"""

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from . import dataset
from .engine import backward_chain, forward_chain
from .knowledge_base import (
    AVAILABLE_GOALS,
    ISSUE_LABELS,
    RECOMMENDATION_LABELS,
    RULES,
    THRESHOLDS,
    normalize_observations,
)
from .schemas import (
    AnalyzeRequest,
    AnalyzeResponse,
    BackwardChainResult,
    Conclusion,
    DatasetReference,
    HealthResponse,
    Recommendation,
    Summary,
)

app = FastAPI(
    title="Smart Agriculture Advisory Expert System",
    description="A small rule-based (forward + backward chaining) agriculture advisor.",
    version="1.0.0",
)

# Allow the local Vite dev server (http://localhost:5173) to call this API.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173", "http://127.0.0.1:5173"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

DISCLAIMER = (
    "This advisory is generated by a demonstration rule-based expert system using "
    "illustrative thresholds. It suggests POSSIBLE causes, not confirmed diagnoses. "
    "Inspect your field and consult a local agronomy expert before taking action. "
    "No pesticide or fertilizer quantities are recommended."
)

# Issue facts that deserve immediate attention rather than routine monitoring.
URGENT_FACTS = {
    "water_stress=possible",
    "stress=heat_and_water",
    "stress=possible_drought_wilting",
    "stress=possible_root_issue",
}

# Display order for issue categories in the UI.
CATEGORY_ORDER = ["irrigation", "stress", "leaf_symptoms", "pest", "soil_nutrient", "dataset"]


def _build_summary(issue_facts: list, fired_count: int) -> Summary:
    """Turn the list of triggered issue facts into a one-line verdict."""
    if not issue_facts:
        return Summary(
            status="normal",
            headline="No problems detected",
            detail=(
                "None of the advisory rules were triggered for these observations. "
                "Continue routine field checks."
            ),
        )
    urgent = [f for f in issue_facts if f in URGENT_FACTS]
    if urgent:
        status = "attention"
        headline = "Attention likely needed"
        detail = (
            f"{len(issue_facts)} possible issue(s) found, including water-related stress. "
            "Check the field soon using the recommendations below."
        )
    else:
        status = "monitor"
        headline = "Worth monitoring"
        detail = (
            f"{len(issue_facts)} possible issue(s) found. Nothing looks urgent, but keep "
            "an eye on the plants listed below."
        )
    detail += f" Conclusions drawn by {fired_count} fired rule(s)."
    return Summary(status=status, headline=headline, detail=detail)


@app.get("/health", response_model=HealthResponse)
def health() -> HealthResponse:
    return HealthResponse(
        status="ok",
        rules_loaded=len(RULES),
        thresholds=THRESHOLDS,
        dataset=dataset.dataset_info(),
    )


@app.get("/crops")
def crops() -> dict:
    """Per-crop typical ranges computed from the bundled CSV (descriptive
    statistics only - no trained model)."""
    return dataset.crops_payload()


@app.get("/goals")
def goals() -> dict:
    """List the goals the UI can offer for the backward-chaining check."""
    return {"goals": [{"fact": fact, "label": label} for fact, label in AVAILABLE_GOALS]}


@app.post("/analyze", response_model=AnalyzeResponse)
def analyze(req: AnalyzeRequest) -> AnalyzeResponse:
    # 1. Normalize raw observations into symbolic facts.
    facts = normalize_observations(
        crop=req.crop,
        soil_moisture=req.soil_moisture,
        temperature=req.temperature,
        rainfall=req.rainfall,
        symptom=req.symptom,
    )

    # 1b. Compare readings against the dataset's typical ranges for this
    #     crop and add the result as more symbolic facts (see dataset.py).
    comparison = dataset.compare(req.crop, req.temperature, req.humidity, req.ph)
    facts.extend(comparison["facts"])

    # 2. Forward chaining: fire rules until no new facts appear.
    fwd = forward_chain(RULES, facts)

    # 3. Group inferred facts into issues and recommendations, with sources.
    fact_rules: dict = {}
    fact_category: dict = {}
    for rule in RULES:
        if rule.rule_id in fwd.fired_rules:
            for key, value in rule.conclusions:
                text = f"{key}={value}"
                fact_rules.setdefault(text, []).append(rule.rule_id)
                fact_category.setdefault(text, rule.category)

    issue_facts = [f for f in fact_rules if f in ISSUE_LABELS]
    issue_facts.sort(key=lambda f: CATEGORY_ORDER.index(fact_category[f]))

    conclusions = [
        Conclusion(
            issue=ISSUE_LABELS[f],
            category=fact_category[f],
            source_rules=fact_rules[f],
        )
        for f in issue_facts
    ]
    recommendations = [
        Recommendation(advice=RECOMMENDATION_LABELS[f], source_rules=fact_rules[f])
        for f in fact_rules
        if f in RECOMMENDATION_LABELS
    ]

    # 4. Optional backward chaining: verify a selected goal against the rules.
    #    The proof starts from the ORIGINAL user facts so it shows real
    #    rule traversal instead of a trivial "already known" hit.
    backward = None
    if req.goal:
        result = backward_chain(RULES, facts, req.goal)
        backward = BackwardChainResult(
            goal=req.goal, supported=result.supported, proof=result.proof
        )

    return AnalyzeResponse(
        summary=_build_summary(issue_facts, len(fwd.fired_rules)),
        conclusions=conclusions,
        recommendations=recommendations,
        fired_rule_ids=fwd.fired_rules,
        inferred_facts=[f"{k}={v}" for k, v in fwd.inferred_facts],
        rules_evaluated=len(RULES),
        reasoning_trace=fwd.trace,
        backward_chain=backward,
        dataset_reference=DatasetReference(
            available=comparison["source"] != "unavailable",
            crop=req.crop,
            source=comparison["source"],
            rows_for_crop=comparison["rows_for_crop"],
            typical_ranges=comparison["ranges"],
            deviations=comparison["deviations"],
        ),
        note=DISCLAIMER,
    )
